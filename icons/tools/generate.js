// Renders every icon in icons.js to a PNG and writes the icon pack's appfilter.xml and drawable.xml.
// Run from this folder: npm install && node generate.js
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const icons = require('./icons');

const SIZE = 256;
const RES = path.join(__dirname, '..', 'src', 'main', 'res');
const ASSETS = path.join(__dirname, '..', 'src', 'main', 'assets');
const OUT = path.join(RES, 'drawable-nodpi');

function glyphPath(glyph) {
  const [set, name] = glyph.split(':');
  const file = set === 'si'
    ? require.resolve(`simple-icons/icons/${name}.svg`)
    : require.resolve(`@mdi/svg/svg/${name}.svg`);
  const svg = fs.readFileSync(file, 'utf8');
  return [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]).join(' ');
}

// The shared tile: near-black with a crimson rim and a faint red glow in the middle.
const tileDefs = `
  <linearGradient id="tile" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#1E1114"/><stop offset="1" stop-color="#0A0708"/>
  </linearGradient>
  <radialGradient id="halo" cx="50%" cy="50%" r="50%">
    <stop offset="0" stop-color="#B3001B" stop-opacity="0.35"/><stop offset="1" stop-color="#B3001B" stop-opacity="0"/>
  </radialGradient>
  <linearGradient id="glyph" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="#FF4D5E"/><stop offset="1" stop-color="#C0101E"/>
  </linearGradient>
  <filter id="glow" x="-40%" y="-40%" width="180%" height="180%">
    <feGaussianBlur stdDeviation="5" result="b"/>
    <feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge>
  </filter>`;
const tile = `<rect x="6" y="6" width="244" height="244" rx="64" fill="url(#tile)"/>`;
const rim = `<rect x="7.5" y="7.5" width="241" height="241" rx="63" fill="none" stroke="#B3001B" stroke-opacity="0.7" stroke-width="3"/>`;

function iconSvg(d) {
  const scale = 120 / 24; // glyphs are drawn on a 24-unit grid
  const offset = (SIZE - 120) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
<defs>${tileDefs}</defs>${tile}
<circle cx="128" cy="128" r="96" fill="url(#halo)"/>
<path transform="translate(${offset} ${offset}) scale(${scale})" d="${d}" fill="url(#glyph)" filter="url(#glow)"/>
${rim}</svg>`;
}

const extras = {
  // Behind and over the original icon of any app without its own: same tile and rim.
  iconback: `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}"><defs>${tileDefs}</defs>${tile}</svg>`,
  iconupon: `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}">${rim}</svg>`,
};

function xmlEscape(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  fs.mkdirSync(path.join(RES, 'xml'), { recursive: true });
  fs.mkdirSync(ASSETS, { recursive: true });

  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE } });
  async function render(name, svg) {
    await page.setContent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`);
    await page.screenshot({ path: path.join(OUT, `${name}.png`), omitBackground: true, clip: { x: 0, y: 0, width: SIZE, height: SIZE } });
  }
  for (const icon of icons) await render(icon.id, iconSvg(glyphPath(icon.glyph)));
  for (const [name, svg] of Object.entries(extras)) await render(name, svg);
  await browser.close();

  const items = icons.flatMap((icon) => icon.components.map((c) =>
    `    <item component="ComponentInfo{${xmlEscape(c)}}" drawable="${icon.id}" />`));
  const appfilter = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate.js from tools/icons.js. Don't edit by hand. -->
<resources>
    <iconback img1="iconback" />
    <iconupon img1="iconupon" />
    <scale factor="0.62" />
${items.join('\n')}
</resources>
`;
  // Launchers read the appfilter from either place, so ship both.
  fs.writeFileSync(path.join(RES, 'xml', 'appfilter.xml'), appfilter);
  fs.writeFileSync(path.join(ASSETS, 'appfilter.xml'), appfilter);

  const drawables = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate.js. Lists every icon for launchers' icon pickers. -->
<resources>
    <version>1</version>
    <category title="Crimson" />
${icons.map((i) => `    <item drawable="${i.id}" />`).join('\n')}
</resources>
`;
  fs.writeFileSync(path.join(RES, 'xml', 'drawable.xml'), drawables);
  fs.writeFileSync(path.join(ASSETS, 'drawable.xml'), drawables);
  console.log(`Rendered ${icons.length} icons, ${items.length} appfilter entries`);
})();
